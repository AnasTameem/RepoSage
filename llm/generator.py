"""
generator.py - LLM response generation using Google Gemini.

Provides asynchronous answer generation and streaming for codebase RAG queries.
"""
import asyncio
import logging
import os
import sys
from collections.abc import AsyncIterator
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

try:
    from config import GEMINI_API_KEY as CFG_GEMINI_API_KEY
    from config import GEMINI_MODEL as CFG_GEMINI_MODEL
except ImportError:
    CFG_GEMINI_API_KEY = os.getenv("GEMINI_API_KEY", "")
    CFG_GEMINI_MODEL = os.getenv("GEMINI_MODEL", "gemini-3.5-flash")

from google import genai
from google.genai import types
from google.genai.errors import APIError, ClientError, ServerError

from llm.prompt_templates import CODEBASE_RAG_SYSTEM_PROMPT, build_user_prompt

logger = logging.getLogger(__name__)

DEFAULT_MODEL = "gemini-3.5-flash-lite"
FALLBACK_MODELS = [
    "gemini-3.5-flash-lite",
    "gemini-3.5-flash",
    "gemini-3.8-flash",
    "gemini-3.7-flash",
]


class ResponseGenerator:
    """
    Asynchronous LLM response generator powered by Google Gemini.
    Supports both non-streaming and streaming responses with grounded codebase context
    and automatic model fallback if a specific model encounters temporary high-demand spikes.
    """

    def __init__(
        self,
        api_key: str | None = None,
        model: str | None = None,
    ):
        self.api_key = api_key or CFG_GEMINI_API_KEY or os.getenv("GEMINI_API_KEY", "")
        self.model = model or CFG_GEMINI_MODEL or DEFAULT_MODEL
        self._client: genai.Client | None = None

    def _get_client(self) -> genai.Client:
        if not self._client:
            if not self.api_key:
                raise ValueError(
                    "GEMINI_API_KEY is not set. Please set GEMINI_API_KEY in your .env file or environment."
                )
            self._client = genai.Client(api_key=self.api_key)
        return self._client

    async def close(self):
        """Closes the underlying client session if open."""
        if self._client:
            if hasattr(self._client, "close"):
                res = self._client.close()
                if asyncio.iscoroutine(res):
                    await res
            self._client = None

    def _build_config(
        self,
        temperature: float = 0.2,
        max_tokens: int = 2048,
    ) -> types.GenerateContentConfig:
        return types.GenerateContentConfig(
            system_instruction=CODEBASE_RAG_SYSTEM_PROMPT,
            temperature=temperature,
            max_output_tokens=max_tokens,
        )

    async def generate(
        self,
        query: str,
        context: str,
        history: list[dict[str, str]] | None = None,
        temperature: float = 0.2,
        max_tokens: int = 2048,
    ) -> str:
        """
        Generates a complete response for a user query grounded in retrieved code context.
        """
        client = self._get_client()
        user_prompt = build_user_prompt(query, context, history)
        config = self._build_config(temperature=temperature, max_tokens=max_tokens)

        models_to_try = [self.model] + [m for m in FALLBACK_MODELS if m != self.model]
        for attempt_idx, attempt_model in enumerate(models_to_try):
            try:
                response = await client.aio.models.generate_content(
                    model=attempt_model,
                    contents=user_prompt,
                    config=config,
                )
                return response.text or ""
            except (ClientError, ServerError, APIError) as exc:
                is_recoverable = getattr(exc, "code", None) in (429, 503) or "demand" in str(exc).lower() or "503" in str(exc)
                if is_recoverable and attempt_idx < len(models_to_try) - 1:
                    next_model = models_to_try[attempt_idx + 1]
                    logger.warning(
                        f"[ResponseGenerator] Model '{attempt_model}' unavailable ({exc}). Auto-falling back to '{next_model}'..."
                    )
                    await asyncio.sleep(1)
                    continue
                logger.error(f"[ResponseGenerator] Gemini API error with model '{attempt_model}': {exc}")
                raise
        return ""

    async def generate_stream(
        self,
        query: str,
        context: str,
        history: list[dict[str, str]] | None = None,
        temperature: float = 0.2,
        max_tokens: int = 2048,
    ) -> AsyncIterator[str]:
        """
        Streams token chunks as they are generated by Gemini.
        Yields string tokens for real-time console or UI output.
        Automatically falls back to alternate Gemini models if one experiences a temporary demand spike.
        """
        client = self._get_client()
        user_prompt = build_user_prompt(query, context, history)
        config = self._build_config(temperature=temperature, max_tokens=max_tokens)

        models_to_try = [self.model] + [m for m in FALLBACK_MODELS if m != self.model]
        for attempt_idx, attempt_model in enumerate(models_to_try):
            try:
                stream = await client.aio.models.generate_content_stream(
                    model=attempt_model,
                    contents=user_prompt,
                    config=config,
                )
                async for chunk in stream:
                    if chunk.text:
                        yield chunk.text
                return
            except (ClientError, ServerError, APIError) as exc:
                is_recoverable = getattr(exc, "code", None) in (429, 503) or "demand" in str(exc).lower() or "503" in str(exc)
                if is_recoverable and attempt_idx < len(models_to_try) - 1:
                    next_model = models_to_try[attempt_idx + 1]
                    logger.warning(
                        f"[ResponseGenerator] Model '{attempt_model}' unavailable ({exc}). Auto-falling back to '{next_model}'..."
                    )
                    await asyncio.sleep(1)
                    continue
                logger.error(f"[ResponseGenerator] Gemini streaming error with model '{attempt_model}': {exc}")
                raise
